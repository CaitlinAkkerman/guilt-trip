// Guilt Trip service worker: network first, falls back to the cache when offline.
const CACHE = "guilt-trip-v1";
const FILES = ["./", "./index.html", "./manifest.webmanifest", "./icon-192.png", "./icon-512.png"];

self.addEventListener("install", e => {
  e.waitUntil(caches.open(CACHE).then(c => c.addAll(FILES)));
  self.skipWaiting();
});

self.addEventListener("activate", e => {
  e.waitUntil(
    caches.keys().then(keys => Promise.all(keys.filter(k => k !== CACHE).map(k => caches.delete(k))))
  );
  self.clients.claim();
});

self.addEventListener("fetch", e => {
    if (e.request.method !== "GET") return;
  // Only cache our own files and the Supabase library; never API responses (they hold user data)
  const url = new URL(e.request.url);
  if (url.origin !== location.origin && url.hostname !== "cdn.jsdelivr.net") return;
  e.respondWith(
    fetch(e.request)
      .then(res => {
        const copy = res.clone();
        caches.open(CACHE).then(c => c.put(e.request, copy));
        return res;
      })
      .catch(() => caches.match(e.request))
  );
});
